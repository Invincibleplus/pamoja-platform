import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const appApiDir = path.join(rootDir, 'app', 'api');
const stashApiDir = path.join(rootDir, '.cf-api-stash');
const openNextDir = path.join(rootDir, '.open-next');
const assetsDir = path.join(openNextDir, 'assets');
const workerFile = path.join(openNextDir, 'worker.js');

function restoreApiDir() {
  try {
    if (fs.existsSync(stashApiDir) && !fs.existsSync(appApiDir)) {
      fs.renameSync(stashApiDir, appApiDir);
    }
  } catch (err) {
    console.error('Failed to restore app/api directory:', err);
  }
}

process.on('exit', restoreApiDir);
process.on('SIGINT', () => {
  restoreApiDir();
  process.exit(1);
});
process.on('SIGTERM', () => {
  restoreApiDir();
  process.exit(1);
});

async function main() {
  const indexHtmlPath = path.join(assetsDir, 'index.html');
  const isFreshStaticBuild =
    fs.existsSync(indexHtmlPath) &&
    !process.argv.includes('--force') &&
    Date.now() - fs.statSync(indexHtmlPath).mtimeMs < 120_000;

  if (isFreshStaticBuild) {
    console.log('✓ Reusing fresh .open-next/assets static build and refreshing worker.js...');
  } else {
    console.log('▶ Building Pamoja Platform static assets + native Cloudflare Worker...');

    // Clean previous .open-next output
    fs.rmSync(openNextDir, { recursive: true, force: true });

    try {
      // Temporarily stash app/api so Next.js output: 'export' compiles all pages statically
      if (fs.existsSync(appApiDir)) {
        if (fs.existsSync(stashApiDir)) {
          fs.rmSync(stashApiDir, { recursive: true, force: true });
        }
        fs.renameSync(appApiDir, stashApiDir);
      }

      const nextBin = path.join(rootDir, 'node_modules', 'next', 'dist', 'bin', 'next');
      const fixScript = path.join(__dirname, 'windows-fs-fix.cjs').replace(/\\/g, '/');
      const isWindows = process.platform === 'win32';
      const existingNodeOptions = process.env.NODE_OPTIONS || '';
      const nodeOptions =
        isWindows && fs.existsSync(path.join(__dirname, 'windows-fs-fix.cjs'))
          ? `${existingNodeOptions} --require "${fixScript}"`.trim()
          : existingNodeOptions;

      const res = spawnSync(process.execPath, [nextBin, 'build'], {
        cwd: rootDir,
        stdio: 'inherit',
        env: {
          ...process.env,
          CF_STATIC_EXPORT: '1',
          NODE_OPTIONS: nodeOptions,
        },
      });

      if (res.status !== 0) {
        throw new Error(`next build exited with code ${res.status}`);
      }
    } finally {
      restoreApiDir();
    }

    // If Next.js placed exported files in out/, move them to .open-next/assets
    const outDir = path.join(rootDir, 'out');
    if (fs.existsSync(path.join(outDir, 'index.html')) && !fs.existsSync(indexHtmlPath)) {
      fs.mkdirSync(openNextDir, { recursive: true });
      fs.cpSync(outDir, assetsDir, { recursive: true });
    }
  }

  if (!fs.existsSync(path.join(assetsDir, 'index.html'))) {
    throw new Error('Expected .open-next/assets/index.html to be generated by Next.js static export.');
  }

  // Remove any server build cache files inside .open-next/assets that don't need to be uploaded as static assets
  for (const internalDir of ['cache', 'server', 'types', ' diagnostics']) {
    const target = path.join(assetsDir, internalDir.trim());
    if (fs.existsSync(target)) {
      fs.rmSync(target, { recursive: true, force: true });
    }
  }
  for (const traceFile of ['trace', 'build-manifest.json', 'app-build-manifest.json', 'react-loadable-manifest.json', 'package.json', 'export-detail.json', 'images-manifest.json', 'prerender-manifest.json', 'routes-manifest.json', 'required-server-files.json']) {
    const target = path.join(assetsDir, traceFile);
    if (fs.existsSync(target)) {
      fs.rmSync(target, { force: true });
    }
  }

  // Copy lib/seedCourses.js and app/api/ai/route.js into .open-next/server-ai/
  const serverAiDir = path.join(openNextDir, 'server-ai');
  const serverLibDir = path.join(openNextDir, 'lib');
  fs.mkdirSync(serverAiDir, { recursive: true });
  fs.mkdirSync(serverLibDir, { recursive: true });

  fs.copyFileSync(
    path.join(rootDir, 'lib', 'seedCourses.js'),
    path.join(serverLibDir, 'seedCourses.js')
  );

  const rawAiRoute = fs.readFileSync(path.join(rootDir, 'app', 'api', 'ai', 'route.js'), 'utf8');
  const patchedAiRoute = rawAiRoute.replace(
    /from\s+['"]\.\.\/\.\.\/\.\.\/lib\/seedCourses(?:\.js)?['"]/g,
    "from '../lib/seedCourses.js'"
  );
  fs.writeFileSync(path.join(serverAiDir, 'route.js'), patchedAiRoute, 'utf8');

  // Write the native Cloudflare Worker entry-point (.open-next/worker.js)
  const workerSource = `import { GET as handleAiGet, POST as handleAiPost } from './server-ai/route.js';

export default {
  async fetch(request, env, ctx) {
    try {
      // Hydrate environment variables from Cloudflare Worker env into process.env if available
      if (typeof process !== 'undefined' && process.env && env) {
        for (const key of ['GEMINI_API_KEY', 'GOOGLE_API_KEY', 'NEXT_PUBLIC_GEMINI_API_KEY']) {
          if (env[key] && typeof env[key] === 'string') {
            process.env[key] = env[key];
          }
        }
      }

      const url = new URL(request.url);
      const pathname = url.pathname;

      // 1. Handle /api/ai directly at the Cloudflare Edge
      if (pathname === '/api/ai' || pathname === '/api/ai/') {
        if (request.method === 'OPTIONS') {
          return new Response(null, {
            status: 204,
            headers: {
              'Access-Control-Allow-Origin': '*',
              'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
              'Access-Control-Allow-Headers': 'Content-Type, Authorization',
            },
          });
        }
        if (request.method === 'GET') {
          return await handleAiGet(request);
        }
        if (request.method === 'POST') {
          return await handleAiPost(request);
        }
        return Response.json({ status: 'error', message: 'Method not allowed' }, { status: 405 });
      }

      // 2. Serve static assets and pre-rendered pages from Cloudflare ASSETS binding
      if (env && env.ASSETS) {
        const isRscRequest =
          pathname.endsWith('.txt') ||
          request.headers.get('RSC') === '1' ||
          url.searchParams.has('_rsc');

        // If Next.js App Router requests an RSC payload on a clean URL, resolve the exported .txt flight file first
        if (isRscRequest && !pathname.endsWith('.txt') && !pathname.startsWith('/_next/')) {
          const rscUrl = new URL(url.toString());
          const trimmedPath = pathname.endsWith('/') && pathname.length > 1 ? pathname.slice(0, -1) : pathname;
          const cleanPath = trimmedPath === '/' ? '/index' : trimmedPath;
          rscUrl.pathname = cleanPath + '.txt';
          const rscResponse = await env.ASSETS.fetch(new Request(rscUrl.toString(), request));
          if (rscResponse.status !== 404) {
            return rscResponse;
          }
        }

        let assetResponse = await env.ASSETS.fetch(request);
        if (assetResponse.status !== 404) {
          return assetResponse;
        }

        // Try appending .html for clean route paths (e.g. /labs -> /labs.html)
        if (!pathname.endsWith('/') && !pathname.includes('.')) {
          const htmlUrl = new URL(url.toString());
          htmlUrl.pathname = pathname + '.html';
          assetResponse = await env.ASSETS.fetch(new Request(htmlUrl.toString(), request));
          if (assetResponse.status !== 404) {
            return assetResponse;
          }
        }

        // Dynamic /courses/[id] fallback for newly authored courses in Educator Studio
        if (pathname.startsWith('/courses/')) {
          const fallbackUrl = new URL(url.toString());
          fallbackUrl.pathname = isRscRequest
            ? '/courses/course-peer-ed-hiv.txt'
            : '/courses/course-peer-ed-hiv.html';
          const fallbackResponse = await env.ASSETS.fetch(new Request(fallbackUrl.toString(), request));
          if (fallbackResponse.status !== 404) {
            return fallbackResponse;
          }
        }

        // Serve custom 404 page if available
        const notFoundUrl = new URL(url.toString());
        notFoundUrl.pathname = '/404.html';
        const notFoundResponse = await env.ASSETS.fetch(new Request(notFoundUrl.toString(), request));
        if (notFoundResponse.status !== 404) {
          return new Response(notFoundResponse.body, {
            status: 404,
            headers: notFoundResponse.headers,
          });
        }
      }

      return new Response('Not Found', { status: 404 });
    } catch (err) {
      return Response.json(
        { status: 'error', message: err?.message || 'Internal Worker Error' },
        { status: 500 }
      );
    }
  },
};
`;

  fs.writeFileSync(workerFile, workerSource, 'utf8');
  console.log('✓ Generated .open-next/worker.js and .open-next/assets successfully!');
}

main().catch((err) => {
  restoreApiDir();
  console.error(err);
  process.exit(1);
});

